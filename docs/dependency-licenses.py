#!/usr/bin/env python3
"""Write docs/dependency-licenses.md: the licenses of the Rust crates in the md-render binary.

Usage, from the repository root:

    python3 docs/dependency-licenses.py > docs/dependency-licenses.md
    python3 docs/dependency-licenses.py --target x86_64-unknown-linux-gnu > linux.md

It reads `cargo metadata --format-version 1 --locked` (no network access with an up-to-date
Cargo.lock) and walks the dependency graph from the `md-render` package along normal and build
dependencies, leaving out dev-dependencies. A crate counts as "linked" when its code can end up
in the binary, and as "build" when only build scripts or procedural macros use it. Without
--target, crates for every platform are listed; --target restricts the graph to one target
triple (cargo metadata --filter-platform).

The page lists the license expression of each crate's Cargo.toml. It is a summary, not the
license texts: generate those for a binary release with `cargo about generate` (cargo-about) or
a similar tool.
"""

import argparse
import collections
import json
import os
import subprocess
import sys
import textwrap

ROOT_PACKAGE = "md-render"
WIDTH = 96


def metadata(target):
    cmd = ["cargo", "metadata", "--format-version", "1", "--locked"]
    if target:
        cmd += ["--filter-platform", target]
    out = subprocess.run(cmd, check=True, capture_output=True, text=True).stdout
    return json.loads(out)


def walk(meta):
    """Map package id -> True (can be linked into the binary) or False (build time only)."""
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = next(
        p["id"] for p in meta["packages"] if p["name"] == ROOT_PACKAGE and p["source"] is None
    )

    def is_proc_macro(pid):
        return any("proc-macro" in t["kind"] for t in packages[pid]["targets"])

    linked = {}
    queue = collections.deque([(root, True)])
    while queue:
        pid, runtime = queue.popleft()
        if pid in linked and (linked[pid] or not runtime):
            continue
        linked[pid] = runtime
        for dep in nodes[pid]["deps"]:
            kinds = {k["kind"] for k in dep["dep_kinds"]}
            if kinds <= {"dev"}:
                continue
            child = dep["pkg"]
            child_runtime = runtime and None in kinds and not is_proc_macro(child)
            queue.append((child, child_runtime))
    linked.pop(root)
    return packages, linked


def license_of(pkg):
    if pkg.get("license"):
        return " ".join(pkg["license"].split())
    if pkg.get("license_file"):
        return "see " + pkg["license_file"]
    return "(none given)"


def link_of(pkg):
    url = pkg.get("repository") or pkg.get("homepage")
    if url:
        return f"[source]({url})"
    return f"[crates.io](https://crates.io/crates/{pkg['name']})"


def names(pkgs):
    return ", ".join(f"`{p['name']}` {p['version']}" for p in pkgs)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--target", help="restrict the graph to one target triple")
    args = ap.parse_args()

    meta = metadata(args.target)
    packages, linked = walk(meta)
    workspace = {p["id"] for p in meta["packages"] if p["source"] is None}
    rows = sorted(
        (packages[pid] for pid in linked),
        key=lambda p: (p["name"].lower(), p["version"]),
    )
    third_party = [p for p in rows if p["id"] not in workspace]
    counts = collections.Counter(license_of(p) for p in third_party if linked[p["id"]])
    n_linked = sum(1 for p in third_party if linked[p["id"]])
    n_build = len(third_party) - n_linked
    platforms = f"target `{args.target}`" if args.target else "all platforms"

    def w(text):
        sys.stdout.write(text)

    def para(text, bullet=False):
        text = " ".join(text.split())
        if bullet:
            w(textwrap.fill(text, WIDTH, initial_indent="* ", subsequent_indent="  ",
                            break_on_hyphens=False) + "\n")
        else:
            w(textwrap.fill(text, WIDTH, break_on_hyphens=False) + "\n\n")

    w("# Rust dependency licenses\n\n")
    w("<!-- Generated by docs/dependency-licenses.py from `cargo metadata`; do not edit. -->\n\n")
    para(
        "The `md-render` binary statically links the Rust crates below. This page summarizes "
        "their licenses as declared in each crate's `Cargo.toml`; the license texts themselves "
        "are in the crates' sources. Material that md-render ports or embeds from other projects "
        "is covered by [`THIRD_PARTY_NOTICES.md`](../THIRD_PARTY_NOTICES.md) instead."
    )
    para(
        f"Graph: the normal and build dependencies of the `md-render` package for {platforms}, "
        "without dev-dependencies, as locked in `Cargo.lock`. "
        f"**{n_linked} crates** can be linked into the binary (*linked*), and **{n_build}** run "
        "only at build time (*build*: build scripts, procedural macros and their dependencies). "
        "Crates for other operating systems (for example `windows-*`) are listed, but they are "
        "linked only on those systems. The workspace's own `tarfs` crate is BSD-3-Clause, like "
        "md-render."
    )
    w("Regenerate this page after changing dependencies:\n\n")
    w("```sh\npython3 docs/dependency-licenses.py > docs/dependency-licenses.md\n```\n\n")
    para(
        "For a binary release, ship the full license texts next to the binary, for example with "
        "[cargo-about](https://github.com/EmbarkStudios/cargo-about) (`cargo about generate`), "
        "and check the licenses with `cargo deny check licenses`."
    )

    w("## Licenses of the linked crates\n\n")
    w("| License (as declared) | Crates |\n|---|---:|\n")
    for lic, n in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0])):
        w(f"| `{lic}` | {n} |\n")
    w("\n")

    notes = []
    mpl = [p for p in third_party if "MPL" in license_of(p)]
    if mpl:
        text = "**MPL-2.0** (Mozilla Public License 2.0): " + names(
            [p for p in mpl if linked[p["id"]]]
        )
        build_only = [p for p in mpl if not linked[p["id"]]]
        if build_only:
            text += " (linked), and " + names(build_only) + " (build time only)"
        text += (
            ". md-render uses these crates unmodified. Their source code is available from "
            "crates.io and from the repositories linked below."
        )
        notes.append(text)
    cdla = [p for p in third_party if "CDLA" in license_of(p)]
    if cdla:
        notes.append(
            "**CDLA-Permissive-2.0** (Community Data License Agreement, Permissive 2.0): "
            + names(cdla)
            + ". These crates contain Mozilla's list of root certificates as data."
        )
    if notes:
        w("## Notes\n\n")
        for text in notes:
            para(text, bullet=True)
        w("\n")

    w("## All crates\n\n")
    w("| Crate | Version | License (as declared) | Use | Source |\n|---|---|---|---|---|\n")
    root_dir = os.path.realpath(meta["workspace_root"])
    for p in rows:
        if p["id"] in workspace:
            use = "workspace"
            rel = os.path.relpath(os.path.dirname(os.path.realpath(p["manifest_path"])), root_dir)
            source = f"[{rel}](../{rel})"
        else:
            use = "linked" if linked[p["id"]] else "build"
            source = link_of(p)
        w(f"| `{p['name']}` | {p['version']} | `{license_of(p)}` | {use} | {source} |\n")


if __name__ == "__main__":
    main()
